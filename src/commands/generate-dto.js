import { mkdir, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import {
  generateDTOSchemasForRegistry,
  generateJSDocForRegistry,
} from "@kiri-orm/core";
import { buildRegistry } from "../config.js";
import { CliError, UsageError } from "../errors.js";
import { plural } from "../format.js";

const FORMATS = ["both", "json", "jsdoc"];

export default {
  name: "generate:dto",
  summary:
    "Write JSON Schemas (create/update/read) and JSDoc types generated from the models",
  usage: "orm generate:dto [--out <dir>] [--format both|json|jsdoc]",
  options: {
    out: {
      type: "string",
      description:
        "output directory (default: `dtoDir` from the config, else ./dto)",
    },
    format: {
      type: "string",
      description: "which files to write (default both)",
    },
  },
  maxPositionals: 0,

  async run({ values, ctx }) {
    const format = values.format ?? "both";
    if (!FORMATS.includes(format))
      throw new UsageError(
        `--format expects one of ${FORMATS.join(", ")}, got "${format}"`,
      );

    const config = await ctx.loadConfig();
    const registry = buildRegistry(config);
    if (!registry)
      throw new CliError(
        `${config.file} declares no models (set \`models\`, \`modules\` or \`registry\`).`,
      );

    const dir = values.out ? resolve(ctx.cwd, values.out) : config.dtoDir;
    await mkdir(dir, { recursive: true });

    const written = [];
    if (format !== "jsdoc") {
      const file = join(dir, "schemas.json");
      await writeFile(
        file,
        JSON.stringify(generateDTOSchemasForRegistry(registry), null, 2) + "\n",
      );
      written.push(file);
    }
    if (format !== "json") {
      const file = join(dir, "types.js");
      await writeFile(
        file,
        `// Generated by \`orm generate:dto\` - do not edit; regenerate instead.\n\n${generateJSDocForRegistry(registry)}\n`,
      );
      written.push(file);
    }

    ctx.out(
      `Generated DTOs for ${plural(registry.listModels().length, "model")}:`,
    );
    for (const file of written) ctx.out(`  ${relative(ctx.cwd, file)}`);
    return 0;
  },
};
